// Transactional email templates. Ported from the Google Apps Script that used
// to render and send these ("BGC Registration Email", Code.gs, last edited
// 2026-08-31) so the HTML a customer receives is byte-for-byte what the script
// produced. Keep it that way unless a template change is intended: the HTML is
// built by plain concatenation, exactly as the script did, so a diff against
// the old script stays readable.
//
// Everything here is pure — no I/O — so it can be tested directly.

