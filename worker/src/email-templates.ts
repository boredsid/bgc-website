function base64Utf8(s: string): string {
  const bytes = new TextEncoder().encode(s);
  let binary = '';
  // Chunked so the spread never passes too many arguments at once.
  for (let i = 0; i < bytes.length; i += 0x2000) {
    binary += String.fromCharCode(...bytes.subarray(i, i + 0x2000));
  }
  return btoa(binary);
}

export function renderDdSubmissionEmail(data: DdSubmissionEmailPayload): RenderedEmail {
  const recipients = data.to && data.to.length ? data.to : [DD_FALLBACK_RECIPIENT];
  const json = JSON.stringify(data.script_json, null, 2);
  const text =
    'New Demon\'s Draft script submission.\n\n' +
    'Name: ' + data.name + '\n' +
    'Phone: ' + data.phone + '\n' +
    'Email: ' + data.email + '\n' +
    'Submission ID: ' + data.submission_id + '\n\n' +
    'Script JSON is attached and included below.\n\n' + json;
  return {
    to: recipients,
    subject: "Demon's Draft submission — " + data.name,
    text,
    attachments: [{ filename: 'script-' + data.submission_id + '.json', content: base64Utf8(json) }],
  };
}
