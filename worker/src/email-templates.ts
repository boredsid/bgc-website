export function escapeHtml(s: unknown): string {
  return String(s).replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] as string,
  );
}

// --- Bangalore-time formatting -------------------------------------------
//
// The script formatted dates with Java's SimpleDateFormat in Asia/Kolkata.
// India has no daylight saving, so IST is always UTC+5:30: shift the instant
// and read the UTC fields. This deliberately avoids Intl, whose English output
// differs from Java's in ways that would change the email ("Sept" in en-GB,
// and a narrow no-break space before AM/PM in recent ICU versions).

const IST_OFFSET_MS = (5 * 60 + 30) * 60 * 1000;
const MONTHS_SHORT = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const MONTHS_LONG = [
  'January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December',
];
const WEEKDAYS_SHORT = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

interface IstParts {
  year: number;
  month: number; // 0-11
  day: number;
  weekday: number; // 0 = Sunday
  hour: number; // 0-23
  minute: number;
}

function istParts(date: Date): IstParts {
  const ms = date.getTime();
  // The script's Utilities.formatDate threw on an invalid date, so no email
  // went out; do the same rather than send one that reads "NaN".
  if (Number.isNaN(ms)) throw new RangeError('Invalid date');
  const shifted = new Date(ms + IST_OFFSET_MS);
  return {
    year: shifted.getUTCFullYear(),
    month: shifted.getUTCMonth(),
    day: shifted.getUTCDate(),
    weekday: shifted.getUTCDay(),
    hour: shifted.getUTCHours(),
    minute: shifted.getUTCMinutes(),
  };
}

function pad2(n: number): string {
  return n < 10 ? '0' + n : String(n);
}

// yyyy-MM-dd
function istDayKey(p: IstParts): string {
  return p.year + '-' + pad2(p.month + 1) + '-' + pad2(p.day);
}

// h:mm a
function istTime(p: IstParts): string {
  const h12 = p.hour % 12 === 0 ? 12 : p.hour % 12;
  return h12 + ':' + pad2(p.minute) + ' ' + (p.hour < 12 ? 'AM' : 'PM');
}

/**
 * Bangalore-time labels for an event, covering all-day and multi-day events.
 * Port of the script's formatEventWhen; the comments show each date shape.
 */
export function formatEventWhen(event: {
  date: string;
  end_date: string | null;
  is_all_day: boolean;
}): { dateStr: string; timeStr: string } {
  const start = istParts(new Date(event.date));
  const end = event.end_date ? istParts(new Date(event.end_date)) : null;

  const startDay = istDayKey(start);
  const endDay = end ? istDayKey(end) : startDay;
  const multiDay = endDay !== startDay;

  let dateStr: string;
  if (!multiDay || !end) {
    // Sat, 31 Oct 2026
    dateStr = WEEKDAYS_SHORT[start.weekday] + ', ' + start.day + ' ' + MONTHS_SHORT[start.month] + ' ' + start.year;
  } else if (start.year !== end.year) {
    // 30 Dec 2026 – 2 Jan 2027
    dateStr =
      start.day + ' ' + MONTHS_SHORT[start.month] + ' ' + start.year + ' – ' +
      end.day + ' ' + MONTHS_SHORT[end.month] + ' ' + end.year;
  } else if (start.month !== end.month) {
    // 28 Sep – 2 Oct 2026
    dateStr =
      start.day + ' ' + MONTHS_SHORT[start.month] + ' – ' +
      end.day + ' ' + MONTHS_SHORT[end.month] + ' ' + end.year;
  } else {
    // 5 – 7 Sep 2026
    dateStr = start.day + ' – ' + end.day + ' ' + MONTHS_SHORT[end.month] + ' ' + end.year;
  }

  let timeStr: string;
  if (event.is_all_day) {
    timeStr = 'All day';
  } else {
    timeStr = istTime(start);
    if (end) {
      const endTime = istTime(end);
      if (endTime !== timeStr) timeStr = timeStr + ' – ' + endTime;
    }
  }

  return { dateStr, timeStr };
}

// d MMMM yyyy, for a YYYY-MM-DD date read as Bangalore midnight.
function formatLongIstDate(isoDate: string): string {
  const p = istParts(new Date(isoDate + 'T00:00:00+05:30'));
  return p.day + ' ' + MONTHS_LONG[p.month] + ' ' + p.year;
}

// --- Shared blocks ---------------------------------------------------------

function paymentBlockHtml(totalAmount: number, upi: { id: string }, paymentUrl: string): string {
  // upi is only read when something is owed, as in the script.
  if (!(totalAmount > 0)) return '';
  // payment_url goes in unescaped, as the script did: the worker builds it
  // with encodeURIComponent, and escaping would turn its & into &amp;.
  const buttonHtml = paymentUrl
    ? '<a href="' + paymentUrl + '" style="display:inline-block;background:#F47B20;color:#fff;text-decoration:none;padding:12px 24px;border-radius:6px;font-weight:bold;font-size:15px;">Complete payment</a>'
    : '';
  return (
    '<table style="width:100%;border-collapse:collapse;margin:24px 0;background:#FFF8F0;border:2px solid #1A1A1A;border-radius:8px;">' +
      '<tr><td style="padding:20px;">' +
        '<div style="font-size:13px;text-transform:uppercase;letter-spacing:1px;color:#999;margin-bottom:8px;">If you haven\'t paid yet</div>' +
        '<div style="font-family:monospace;font-size:15px;color:#1A1A1A;margin-bottom:4px;">UPI: ' + escapeHtml(upi.id) + '</div>' +
        '<div style="font-family:monospace;font-size:15px;color:#1A1A1A;margin-bottom:16px;">Amount: ₹' + totalAmount + '</div>' +
        buttonHtml +
        (buttonHtml ? '<div style="color:#999;font-size:13px;margin-top:12px;">Already paid? You can ignore this section.</div>' : '') +
      '</td></tr>' +
    '</table>'
  );
}

function venueHtml(event: { venue_name: string; venue_area: string | null }): string {
  return event.venue_area
    ? escapeHtml(event.venue_name) + ' · ' + escapeHtml(event.venue_area)
    : escapeHtml(event.venue_name);
}

function whatsappLine(): string {
  return 'Questions? Reply to this email or WhatsApp <a href="https://wa.me/' + WHATSAPP_NUMBER_DIGITS + '" style="color:#F47B20;">' + WHATSAPP_NUMBER_DISPLAY + '</a>.';
}

